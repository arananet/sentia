function passLogChecks(rel, label) {
  assert.ok(exists(rel), `${rel} is missing`);
  const log = read(rel);
  assert.match(log, /console errors: 0\b/, `${label}: zero console errors`);
  assert.match(log, /page errors: 0\b/, `${label}: zero page errors`);
  assert.match(log, /scene ready: true/, `${label}: scene ready`);
  assert.match(log, /GLB \/models\/patch-one\.glb: status 200; bytes (\d+)/, `${label}: GLB route fetched`);
  const bytes = Number(log.match(/GLB \/models\/patch-one\.glb: status 200; bytes (\d+)/)[1]);
  assert.ok(bytes <= BUDGET, `${label}: logged GLB bytes ${bytes} within budget`);
  const nodes = log.match(/loaded nodes: 5; ([^\n]+)/);
  assert.ok(nodes, `${label}: five loaded nodes recorded`);
  assert.deepEqual(nodes[1].split(';').map((s) => s.trim()), NAMES, `${label}: the five named nodes are recorded`);
  assert.match(log, /Bundled Worker:/, `${label}: the capture drove the bundled Worker output`);
  assert.doesNotMatch(log, /src\/take-apart-client\.js|src\/index\.js/, `${label}: no unbundled source loaded`);
  return log;
}

test('web-render-finish S7: before and after browser pass logs record zero errors, scene ready, GLB fetched, five named nodes, bundled output', () => {
  passLogChecks('evidence/web-render-finish/before/browser-pass.log', 'before');
  const after = passLogChecks('evidence/web-render-finish/after/browser-pass.log', 'after');
  assert.match(after, /gauge comparison: PASS/, 'after: gauge comparison passes');
  passLogChecks('evidence/take-apart/browser-pass.log', 'standard capture');
});

