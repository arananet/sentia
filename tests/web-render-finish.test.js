// ---------------------------------------------------------------- S2 (R6)
test('web-render-finish S2: five FACTS nodes in stack order at layerCenterMm(t=0) within 0.01, 36 mm footprint, 2.5 mm profile', async () => {
  const { bytes } = await moduleInfo();
  const gltf = parseGlb(bytes);
  const top = gltf.scenes[gltf.scene ?? 0].nodes;
  assert.deepEqual(top.map((i) => gltf.nodes[i].name), NAMES, 'exactly the five FACTS names in stack order');
  top.forEach((idx, k) => {
    const t = gltf.nodes[idx].translation || [0, 0, 0];
    assert.ok(Math.abs(t[0]) <= 0.01 && Math.abs(t[2]) <= 0.01, `${NAMES[k]} x and z are 0`);
    assert.ok(Math.abs(t[1] - M.layerCenterMm(k, 0)) <= 0.01, `${NAMES[k]} y ${t[1]} vs layerCenterMm ${M.layerCenterMm(k, 0)}`);
  });
  const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (const idx of top) {
    const b = worldBounds(gltf, idx);
    for (let a = 0; a < 3; a++) { lo[a] = Math.min(lo[a], b.lo[a]); hi[a] = Math.max(hi[a], b.hi[a]); }
  }
  assert.ok(Math.abs(hi[0] - lo[0] - 36) <= 0.5, `footprint x ${(hi[0] - lo[0]).toFixed(3)}`);
  assert.ok(Math.abs(hi[2] - lo[2] - 36) <= 0.5, `footprint z ${(hi[2] - lo[2]).toFixed(3)}`);
  assert.ok(Math.abs(hi[1] - lo[1] - 2.5) <= 0.1, `profile ${(hi[1] - lo[1]).toFixed(3)}`);
  // Layer thicknesses are frozen (local bounds of each layer, descendants only).
  top.forEach((idx, k) => {
    const n = gltf.nodes[idx];
    const kids = (n.children || []).map((c) => worldBounds(gltf, c));
    const l = Math.min(...kids.map((b) => b.lo[1])), h = Math.max(...kids.map((b) => b.hi[1]));
    const slack = k === 4 ? 0.3 : 0.1;
    assert.ok(h - l >= M.LAYERS[k].thicknessMm * 0.4 && h - l <= M.LAYERS[k].thicknessMm + slack, `${NAMES[k]} thickness ${(h - l).toFixed(3)}`);
  });
});

// ---------------------------------------------------------------- S3 (R5)
test('web-render-finish S3: asset unchanged equals the wo-gh-12 loopback asset; asset changed has reproducibility re-proven', async () => {
  const info = await moduleInfo();
  if (!(await assetChanged())) {
    assert.equal(info.bytes.length, BASE_GLB.bytes, 'unchanged asset keeps its byte size');
    assert.equal(info.moduleSha, BASE_MODULE_SHA, 'committed module is byte identical to the wo-gh-12 loopback asset');
    return;
  }
  const log = 'evidence/web-render-finish/reproducibility.log';
  assert.ok(exists(log), `${log} is missing: the asset changed, reproducibility must be re-proven`);
  const text = read(log);
  const exports = [...text.matchAll(/export\s+(\d+)[^\n]*GLB SHA256 ([0-9a-f]{64})[^\n]*bytes (\d+)[^\n]*exit 0/gi)];
  assert.ok(exports.length >= 2, 'the log records two consecutive full build_all.py exports, each exit 0');
  assert.equal(exports[0][2], exports[1][2], 'two exports have the same GLB SHA256');
  assert.equal(exports[0][2], info.glbSha, 'the export SHA256 equals the committed GLB bytes');
  assert.equal(Number(exports[0][3]), info.bytes.length, 'the logged byte size equals the committed GLB size');
  const mods = [...text.matchAll(/module SHA256 ([0-9a-f]{64})/gi)].map((m) => m[1]);
  assert.ok(mods.length >= 2 && mods.every((m) => m === info.moduleSha), 'committed src/patch-one-glb.js equals the export module byte for byte');
  assert.match(text, /PASS/);
  assert.match(text, /4\.5\.15/, 'the log names the pinned Blender 4.5.15');
});

