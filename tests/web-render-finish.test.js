function parseGlb(buf) {
  assert.equal(buf.readUInt32LE(0), 0x46546c67, 'GLB magic "glTF"');
  assert.equal(buf.readUInt32LE(8), buf.length, 'GLB header length equals byte length');
  const jlen = buf.readUInt32LE(12);
  assert.equal(buf.readUInt32LE(16), 0x4e4f534a, 'first chunk is JSON');
  return JSON.parse(buf.toString('utf8', 20, 20 + jlen));
}
async function moduleInfo() {
  assert.ok(exists('src/patch-one-glb.js'), 'src/patch-one-glb.js is missing');
  const mod = await import('../src/patch-one-glb.js');
  const b64 = Object.values(mod).find((v) => typeof v === 'string');
  assert.ok(b64, 'src/patch-one-glb.js exports the base64 string');
  const bytes = Buffer.from(b64, 'base64');
  return { bytes, glbSha: sha(bytes), moduleSha: sha(fs.readFileSync(root('src/patch-one-glb.js'))) };
}
const assetChanged = async () => (await moduleInfo()).glbSha !== BASE_GLB.sha256;

// World bounds of a subtree from POSITION accessor min and max (nodes carry translation only here;
// the frozen product test in take-apart-product-model keeps the full matrix reader).
function worldBounds(gltf, idx, off = [0, 0, 0]) {
  const n = gltf.nodes[idx];
  const t = n.translation || [0, 0, 0];
  const o = [off[0] + t[0], off[1] + t[1], off[2] + t[2]];
  const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  const add = (l, h) => { for (let i = 0; i < 3; i++) { lo[i] = Math.min(lo[i], l[i]); hi[i] = Math.max(hi[i], h[i]); } };
  if (n.mesh != null) {
    assert.ok(!n.rotation && !n.scale && !n.matrix, 'descendant nodes are plain translations');
    for (const p of gltf.meshes[n.mesh].primitives) {
      const a = gltf.accessors[p.attributes.POSITION];
      add(a.min.map((v, i) => v + o[i]), a.max.map((v, i) => v + o[i]));
    }
  }
  for (const c of n.children || []) { const b = worldBounds(gltf, c, o); if (b) add(b.lo, b.hi); }
  return lo[0] === Infinity ? null : { lo, hi };
}

